static inline uint32_t zy100_ble_connection_detail_pack(uint8_t stage,
                                                        uint8_t reason,
                                                        uint16_t retry_ms)
{
    return (uint32_t)stage |
           ((uint32_t)reason << 8) |
           ((uint32_t)retry_ms << 16);
}

