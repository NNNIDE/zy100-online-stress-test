static inline uint32_t zy100_ble_ctrl_low_battery_detail_pack(
    uint8_t percent,
    uint16_t battery_mv)
{
    return ((uint32_t)ZY100_BLE_STATE_DETAIL_LOW_BATTERY_REASON <<
            ZY100_BLE_STATE_DETAIL_REASON_SHIFT) |
           ((uint32_t)percent << ZY100_BLE_STATE_DETAIL_PERCENT_SHIFT) |
           ((uint32_t)battery_mv <<
            ZY100_BLE_STATE_DETAIL_BATTERY_MV_SHIFT);
}

