#ifndef ZY100_ONLINE_RECOVERY_POLICY_H
#define ZY100_ONLINE_RECOVERY_POLICY_H

#if defined(ZY100_ONLINE_RECOVERY_POLICY_HOST_TEST)
typedef enum
{
    ZY100_ONLINE_STOP_REASON_NONE = 0U,
    ZY100_ONLINE_STOP_REASON_HOST_STOP = 1U,
    ZY100_ONLINE_STOP_REASON_DISCONNECT = 2U,
    ZY100_ONLINE_STOP_REASON_ACK_TIMEOUT = 3U,
    ZY100_ONLINE_STOP_REASON_SPOOL_FULL = 4U,
    ZY100_ONLINE_STOP_REASON_INTERNAL = 5U,
    ZY100_ONLINE_STOP_REASON_TRANSPORT_UNAVAILABLE = 6U,
    ZY100_ONLINE_STOP_REASON_TX_STALL = 7U,
    ZY100_ONLINE_STOP_REASON_TX_COMPLETE_FAILED = 8U,
    ZY100_ONLINE_STOP_REASON_CAPTURE_FATAL = 9U,
    ZY100_ONLINE_STOP_REASON_LOW_BATTERY = 10U,
    ZY100_ONLINE_STOP_REASON_USER_SHUTDOWN = 11U,
    ZY100_ONLINE_STOP_REASON_FLASH_IO = 12U,
    ZY100_ONLINE_STOP_REASON_RESET_RECOVERY = 13U,
} zy100_online_stop_reason_t;
#else
#include "zy100_online_stream.h"
#endif

typedef enum
{
    ZY100_ONLINE_RECOVERY_NONE = 0U,
    ZY100_ONLINE_RECOVERY_GRACEFUL_END,
    ZY100_ONLINE_RECOVERY_ABORT_RECOVERABLE,
    ZY100_ONLINE_RECOVERY_ABORT_SHUTDOWN,
    ZY100_ONLINE_RECOVERY_ABORT_HARD_FAULT,
} zy100_online_recovery_mode_t;

static inline zy100_online_recovery_mode_t
zy100_online_recovery_mode_for_reason(zy100_online_stop_reason_t reason)
{
    switch (reason)
    {
    case ZY100_ONLINE_STOP_REASON_NONE:
        return ZY100_ONLINE_RECOVERY_NONE;
    case ZY100_ONLINE_STOP_REASON_HOST_STOP:
        return ZY100_ONLINE_RECOVERY_GRACEFUL_END;
    case ZY100_ONLINE_STOP_REASON_LOW_BATTERY:
    case ZY100_ONLINE_STOP_REASON_USER_SHUTDOWN:
        return ZY100_ONLINE_RECOVERY_ABORT_SHUTDOWN;
    case ZY100_ONLINE_STOP_REASON_FLASH_IO:
        return ZY100_ONLINE_RECOVERY_ABORT_HARD_FAULT;
    default:
        return ZY100_ONLINE_RECOVERY_ABORT_RECOVERABLE;
    }
}

#endif
