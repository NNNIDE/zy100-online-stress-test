#ifndef ZY100_INTERNAL_FLASH_LAYOUT_H
#define ZY100_INTERNAL_FLASH_LAYOUT_H

#include "flash_map.h"
#include "../app_flags.h"

#define ZY100_INTERNAL_FLASH_SECTOR_BYTES       4096UL

#define ZY100_OFFLINE_V2_MARKER_REGION_OFFSET   0UL
#define ZY100_OFFLINE_V2_MARKER_REGION_BYTES    (8UL * 1024UL)
#define ZY100_OFFLINE_V2_MARKER_PRIMARY_OFFSET  ZY100_OFFLINE_V2_MARKER_REGION_OFFSET
#define ZY100_OFFLINE_V2_MARKER_BACKUP_OFFSET   \
    (ZY100_OFFLINE_V2_MARKER_PRIMARY_OFFSET + ZY100_INTERNAL_FLASH_SECTOR_BYTES)

#define ZY100_SYSTEM_INFO_REGION_OFFSET         0x00002000UL
#define ZY100_SYSTEM_INFO_REGION_BYTES          (8UL * 1024UL)
#define ZY100_SYSTEM_INFO_SLOT_BYTES            ZY100_INTERNAL_FLASH_SECTOR_BYTES
#define ZY100_SYSTEM_INFO_PRIMARY_OFFSET        ZY100_SYSTEM_INFO_REGION_OFFSET
#define ZY100_SYSTEM_INFO_BACKUP_OFFSET         \
    (ZY100_SYSTEM_INFO_REGION_OFFSET + ZY100_SYSTEM_INFO_SLOT_BYTES)

#define ZY100_SYSTEM_INFO_REGION_ABS_ADDR       \
    (USER_DATA1_ADDR + ZY100_SYSTEM_INFO_REGION_OFFSET)
#define ZY100_SYSTEM_INFO_REGION_END_OFFSET     \
    (ZY100_SYSTEM_INFO_REGION_OFFSET + ZY100_SYSTEM_INFO_REGION_BYTES)
#define ZY100_SYSTEM_INFO_REGION_END_ABS_ADDR   \
    (USER_DATA1_ADDR + ZY100_SYSTEM_INFO_REGION_END_OFFSET)

#define ZY100_MFG_REGION_OFFSET_CANDIDATE       0x00004000UL
#ifndef ZY100_MFG_REGION_OFFSET
#define ZY100_MFG_REGION_OFFSET                 ZY100_MFG_REGION_OFFSET_CANDIDATE
#endif
#define ZY100_MFG_REGION_BYTES                  (8UL * 1024UL)
#define ZY100_MFG_SLOT_BYTES                    ZY100_INTERNAL_FLASH_SECTOR_BYTES
#define ZY100_MFG_PRIMARY_OFFSET                ZY100_MFG_REGION_OFFSET
#define ZY100_MFG_BACKUP_OFFSET                 \
    (ZY100_MFG_REGION_OFFSET + ZY100_MFG_SLOT_BYTES)
#define ZY100_MFG_REGION_END_OFFSET             \
    (ZY100_MFG_REGION_OFFSET + ZY100_MFG_REGION_BYTES)

#if ZY100_LEGACY_OFFLINE_ENABLE || ZY100_FINAL_EDGE_MODE_ENABLE
#error "24KB USER_DATA1 does not support Legacy internal metadata"
#endif

#if (USER_DATA1_ADDR != 0x008FA000UL) || (USER_DATA1_SIZE != 0x6000UL) || \
    ((USER_DATA1_ADDR + USER_DATA1_SIZE) != 0x00900000UL)
#error "ZY100 requires the 24KB USER_DATA1 layout at the end of 1MiB Flash"
#endif

#if ((ZY100_OFFLINE_V2_MARKER_REGION_OFFSET % ZY100_INTERNAL_FLASH_SECTOR_BYTES) != 0UL) || \
    (ZY100_OFFLINE_V2_MARKER_REGION_BYTES != (2UL * ZY100_INTERNAL_FLASH_SECTOR_BYTES)) || \
    ((ZY100_OFFLINE_V2_MARKER_REGION_OFFSET + ZY100_OFFLINE_V2_MARKER_REGION_BYTES) != ZY100_SYSTEM_INFO_REGION_OFFSET) || \
    (ZY100_SYSTEM_INFO_REGION_END_OFFSET != ZY100_MFG_REGION_OFFSET) || \
    (ZY100_MFG_REGION_END_OFFSET != USER_DATA1_SIZE)
#error "Marker, System Info and MFG must occupy six consecutive 4KB sectors"
#endif

#if ((ZY100_SYSTEM_INFO_REGION_OFFSET % ZY100_INTERNAL_FLASH_SECTOR_BYTES) != 0UL)
#error "ZY100 system info region offset must be 4KB aligned"
#endif

#if ((ZY100_SYSTEM_INFO_REGION_BYTES % ZY100_INTERNAL_FLASH_SECTOR_BYTES) != 0UL)
#error "ZY100 system info region size must be 4KB aligned"
#endif

#if (ZY100_SYSTEM_INFO_REGION_BYTES != (2UL * ZY100_INTERNAL_FLASH_SECTOR_BYTES))
#error "ZY100 system info region must be two 4KB sectors"
#endif

#if (ZY100_SYSTEM_INFO_BACKUP_OFFSET != \
     (ZY100_SYSTEM_INFO_PRIMARY_OFFSET + ZY100_SYSTEM_INFO_SLOT_BYTES))
#error "ZY100 system info backup slot must follow primary slot"
#endif

#if ZY100_LEGACY_OFFLINE_ENABLE && (((ZY100_SYSTEM_INFO_REGION_OFFSET + ZY100_SYSTEM_INFO_REGION_BYTES) > \
      ZY100_FINAL_EDGE_META_REGION_BASE_ADDR) && \
     (ZY100_SYSTEM_INFO_REGION_OFFSET < \
      (ZY100_FINAL_EDGE_META_REGION_BASE_ADDR + ZY100_FINAL_EDGE_META_REGION_BYTES)))
#error "ZY100 system info region must not overlap internal meta region"
#endif

#if (ZY100_SYSTEM_INFO_REGION_END_OFFSET > USER_DATA1_SIZE)
#error "ZY100 system info region must stay inside USER_DATA1"
#endif

#if ((ZY100_MFG_REGION_OFFSET % ZY100_INTERNAL_FLASH_SECTOR_BYTES) != 0UL)
#error "ZY100 MFG region offset must be 4KB aligned"
#endif

#if ((ZY100_MFG_REGION_BYTES % ZY100_INTERNAL_FLASH_SECTOR_BYTES) != 0UL)
#error "ZY100 MFG region size must be 4KB aligned"
#endif

#if (ZY100_MFG_REGION_BYTES != (2UL * ZY100_INTERNAL_FLASH_SECTOR_BYTES))
#error "ZY100 MFG region must be two 4KB sectors"
#endif

#if (ZY100_MFG_BACKUP_OFFSET != (ZY100_MFG_PRIMARY_OFFSET + ZY100_MFG_SLOT_BYTES))
#error "ZY100 MFG backup slot must follow primary slot"
#endif

#if ZY100_LEGACY_OFFLINE_ENABLE && (((ZY100_MFG_REGION_OFFSET + ZY100_MFG_REGION_BYTES) > \
      ZY100_FINAL_EDGE_META_REGION_BASE_ADDR) && \
     (ZY100_MFG_REGION_OFFSET < \
      (ZY100_FINAL_EDGE_META_REGION_BASE_ADDR + ZY100_FINAL_EDGE_META_REGION_BYTES)))
#error "ZY100 MFG region must not overlap internal meta region"
#endif

#if (((ZY100_MFG_REGION_OFFSET + ZY100_MFG_REGION_BYTES) > \
      ZY100_SYSTEM_INFO_REGION_OFFSET) && \
     (ZY100_MFG_REGION_OFFSET < ZY100_SYSTEM_INFO_REGION_END_OFFSET))
#error "ZY100 MFG region must not overlap system info region"
#endif

#if (ZY100_MFG_REGION_END_OFFSET > USER_DATA1_SIZE)
#error "ZY100 MFG region must stay inside USER_DATA1"
#endif

#endif /* ZY100_INTERNAL_FLASH_LAYOUT_H */
